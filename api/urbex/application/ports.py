from typing import Protocol


class Repository(Protocol):
    def enqueue_event(self, routing_key: str, message: dict) -> None: ...

    def clear_active_itineraries(self, author_id): ...

    def telegram_user(self, telegram_id: int, name: str, password_hash: str) -> dict: ...
    def get(self, kind: str, id: int, lock: bool = False) -> dict: ...
    def add(self, kind: str, values: dict) -> dict: ...
    def update(self, kind: str, id: int, values: dict) -> dict: ...
    def list(self, kind: str, filters: dict, page: int = 1) -> dict: ...
    def delete(self, kind: str, filters: dict) -> None: ...
    def search(self, filters: dict) -> dict: ...
    def locations(self, query: str) -> dict: ...
    def map(self, filters: dict, zoom: int) -> dict: ...
    def rate_attempt(self, key: str) -> int: ...
    def audit(self, actor: int, action: str, target: str, detail: str) -> None: ...


class PhotoStorage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...
    def get_telegram(self, file_id: str) -> bytes: ...


class Passwords(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, encoded: str | None, password: str) -> bool: ...
